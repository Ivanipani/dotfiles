use std::path::{Path, PathBuf};

use serde::{Deserialize, Serialize};

use crate::config::Config;
use crate::repos::workspaces_root;

pub const FILE_NAME: &str = "workspace.yaml";
pub const AGENTS_FILE_NAME: &str = "AGENTS.md";

/// The intended components of a workspace set. Stored as `workspace.yaml` in
/// the set's directory; it is the source of truth for the set's members.
#[derive(Default, Serialize, Deserialize, PartialEq, Debug)]
pub struct Manifest {
    pub name: String,
    pub projects: Vec<Component>,
    /// Fields only rex-workspace knows (goal, links), kept as they are on save.
    #[serde(flatten)]
    pub extra: serde_yaml_ng::Mapping,
}

#[derive(Clone, Serialize, Deserialize, PartialEq, Debug)]
pub struct Component {
    pub name: String,
    /// Host path of the repository the workspace was added from.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub source: Option<PathBuf>,
}

impl Manifest {
    fn file(config: &Config, mount: &Path, set: &str) -> Option<PathBuf> {
        workspaces_root(config, mount).map(|root| root.join(set).join(FILE_NAME))
    }

    /// `None` when the set has no readable manifest (e.g. it predates them).
    pub fn load(config: &Config, mount: &Path, set: &str) -> Option<Manifest> {
        let text = std::fs::read_to_string(Self::file(config, mount, set)?).ok()?;
        serde_yaml_ng::from_str(&text).ok()
    }

    /// Writes `workspace.yaml` and regenerates the set's `AGENTS.md` beside it.
    pub fn save(&mut self, config: &Config, mount: &Path) -> Result<(), String> {
        self.projects.sort_by(|a, b| a.name.cmp(&b.name));
        let file = Self::file(config, mount, &self.name).ok_or("workspaces_dir is not accessible")?;
        let text = serde_yaml_ng::to_string(self).map_err(|e| e.to_string())?;
        let dir = file.parent().expect("file has a parent");
        std::fs::create_dir_all(dir)
            .and_then(|_| std::fs::write(&file, text))
            .map_err(|e| format!("cannot write {}: {e}", FILE_NAME))?;
        std::fs::write(dir.join(AGENTS_FILE_NAME), self.agents_md())
            .map_err(|e| format!("cannot write {}: {e}", AGENTS_FILE_NAME))
    }

    /// Guidance for coding agents started in the set's directory.
    fn agents_md(&self) -> String {
        let projects: String = self
            .projects
            .iter()
            .map(|c| match &c.source {
                Some(source) => format!("- `{}/` — from `{}`\n", c.name, source.display()),
                None => format!("- `{}/`\n", c.name),
            })
            .collect();
        format!(
            "# Workspace: {name}\n\
             \n\
             This directory is a special-purpose workspace set named `{name}`, created to develop one \
             feature across several projects. It is generated by the zellij-workspace plugin; \
             do not edit this file, it is rewritten whenever the set changes.\n\
             \n\
             ## Layout\n\
             \n\
             Each subdirectory below is a [jujutsu](https://jj-vcs.github.io/jj/) workspace of a \
             separate repository, not a clone. Its source repository shares the same commit graph.\n\
             \n\
             {projects}\
             \n\
             ## Working here\n\
             \n\
             - Use `jj`, never `git`, for version control. Run it inside the project you are changing.\n\
             - Keep changes scoped to the feature this workspace exists for.\n\
             - Each workspace has its own working-copy commit (`@`); changes are committed to the \
             shared repository as soon as `jj` runs. Describe them with `jj describe`.\n\
             - Do not run `jj workspace forget` or delete project directories. Membership is managed \
             through the plugin and `{FILE_NAME}`.\n\
             - Do not touch the source repositories directly.\n",
            name = self.name,
        )
    }

    pub fn contains(&self, name: &str) -> bool {
        self.projects.iter().any(|c| c.name == name)
    }

    pub fn add(&mut self, component: Component) {
        if !self.contains(&component.name) {
            self.projects.push(component);
        }
    }

    pub fn remove(&mut self, name: &str) -> Option<Component> {
        let i = self.projects.iter().position(|c| c.name == name)?;
        Some(self.projects.remove(i))
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn load_then_save_keeps_fields_it_does_not_know() {
        // GIVEN a manifest written by rex-workspace with a goal
        let manifest: Manifest = serde_yaml_ng::from_str("name: set\ngoal: ship\nprojects: []\n").unwrap();
        // WHEN
        let text = serde_yaml_ng::to_string(&manifest).unwrap();
        // THEN
        assert!(text.contains("goal: ship"));
    }

    #[test]
    fn round_trips_through_yaml() {
        let mount = std::env::temp_dir().join(format!("workspace-manifest-{}", std::process::id()));
        std::fs::create_dir_all(mount.join("ws")).unwrap();
        let config = Config { workspaces_dir: "/ws".into(), ..Config::default() };
        let mut manifest = Manifest { name: "set".into(), ..Default::default() };
        manifest.add(Component { name: "b".into(), source: Some("/src/b".into()) });
        manifest.add(Component { name: "a".into(), source: None });
        manifest.save(&config, &mount).unwrap();
        let loaded = Manifest::load(&config, &mount, "set").unwrap();
        assert_eq!(loaded, manifest);
        assert_eq!(loaded.projects[0].name, "a");
        let agents = std::fs::read_to_string(mount.join("ws/set").join(AGENTS_FILE_NAME)).unwrap();
        assert!(agents.contains("# Workspace: set"));
        assert!(agents.contains("- `b/` — from `/src/b`"));
        std::fs::remove_dir_all(mount).unwrap();
    }
}
